import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { ProjectData } from './projectManager';

/**
 * PDF Export System for Quality Improvement Projects
 * Generate professional reports with charts and analysis
 */

export class PDFExporter {
  /**
   * Export complete project as PDF report
   */
  static exportProjectReport(project: ProjectData): void {
    const doc = new jsPDF();
    let yPosition = 20;

    // Title Page
    doc.setFontSize(24);
    doc.setTextColor(59, 130, 246); // Primary blue
    doc.text('Quality Improvement Project Report', 105, yPosition, { align: 'center' });
    
    yPosition += 15;
    doc.setFontSize(16);
    doc.setTextColor(0, 0, 0);
    doc.text(project.name, 105, yPosition, { align: 'center' });
    
    yPosition += 10;
    doc.setFontSize(10);
    doc.setTextColor(100, 100, 100);
    doc.text(project.description || 'No description provided', 105, yPosition, { align: 'center' });
    
    yPosition += 20;
    doc.setFontSize(10);
    doc.text(`Created: ${new Date(project.createdAt).toLocaleDateString()}`, 20, yPosition);
    yPosition += 7;
    doc.text(`Last Updated: ${new Date(project.updatedAt).toLocaleDateString()}`, 20, yPosition);
    yPosition += 7;
    doc.text(`Current Phase: ${project.currentPhase.toUpperCase()}`, 20, yPosition);

    // Project Overview Section
    yPosition += 20;
    this.addSectionHeader(doc, 'Project Overview', yPosition);
    yPosition += 10;
    
    const overviewData = [
      ['Project ID', project.id],
      ['Project Name', project.name],
      ['Current Phase', project.currentPhase.charAt(0).toUpperCase() + project.currentPhase.slice(1)],
      ['Tools Used', Object.keys(project.toolsData).length.toString()],
      ['Status', 'Active'],
    ];

    autoTable(doc, {
      startY: yPosition,
      head: [['Attribute', 'Value']],
      body: overviewData,
      theme: 'grid',
      headStyles: { fillColor: [59, 130, 246] },
    });

    yPosition = (doc as any).lastAutoTable.finalY + 15;

    // Tools Data Summary
    if (Object.keys(project.toolsData).length > 0) {
      doc.addPage();
      yPosition = 20;
      
      this.addSectionHeader(doc, 'Tools & Analysis Summary', yPosition);
      yPosition += 10;

      Object.entries(project.toolsData).forEach(([toolName, toolData]) => {
        if (yPosition > 250) {
          doc.addPage();
          yPosition = 20;
        }

        doc.setFontSize(12);
        doc.setTextColor(59, 130, 246);
        doc.text(this.formatToolName(toolName), 20, yPosition);
        yPosition += 7;

        doc.setFontSize(10);
        doc.setTextColor(0, 0, 0);
        
        const summary = this.generateToolSummary(toolName, toolData);
        const lines = doc.splitTextToSize(summary, 170);
        doc.text(lines, 20, yPosition);
        yPosition += (lines.length * 5) + 10;
      });
    }

    // Project Notes
    if (project.notes) {
      doc.addPage();
      yPosition = 20;
      
      this.addSectionHeader(doc, 'Project Notes', yPosition);
      yPosition += 10;
      
      doc.setFontSize(10);
      const noteLines = doc.splitTextToSize(project.notes, 170);
      doc.text(noteLines, 20, yPosition);
    }

    // Footer on all pages
    const pageCount = doc.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFontSize(8);
      doc.setTextColor(150, 150, 150);
      doc.text(
        `Page ${i} of ${pageCount} | Generated by QualityPro Toolkit`,
        105,
        290,
        { align: 'center' }
      );
    }

    // Save the PDF
    doc.save(`${project.name.replace(/[^a-z0-9]/gi, '_')}_Report_${new Date().toISOString().split('T')[0]}.pdf`);
  }

  /**
   * Export phase-specific report
   */
  static exportPhaseReport(project: ProjectData, phase: string): void {
    const doc = new jsPDF();
    let yPosition = 20;

    doc.setFontSize(20);
    doc.setTextColor(59, 130, 246);
    doc.text(`${phase.toUpperCase()} Phase Report`, 105, yPosition, { align: 'center' });
    
    yPosition += 10;
    doc.setFontSize(14);
    doc.setTextColor(0, 0, 0);
    doc.text(project.name, 105, yPosition, { align: 'center' });
    
    yPosition += 15;

    // Filter tools for this phase
    const phaseTools = Object.entries(project.toolsData).filter(([toolName]) => 
      this.getToolPhase(toolName) === phase
    );

    if (phaseTools.length === 0) {
      doc.setFontSize(12);
      doc.text('No data available for this phase.', 20, yPosition);
    } else {
      phaseTools.forEach(([toolName, toolData]) => {
        if (yPosition > 250) {
          doc.addPage();
          yPosition = 20;
        }

        this.addToolSection(doc, toolName, toolData, yPosition);
        yPosition = (doc as any).lastAutoTable?.finalY + 15 || yPosition + 30;
      });
    }

    doc.save(`${project.name}_${phase}_Report_${new Date().toISOString().split('T')[0]}.pdf`);
  }

  /**
   * Add section header
   */
  private static addSectionHeader(doc: jsPDF, title: string, y: number): void {
    doc.setFontSize(14);
    doc.setTextColor(59, 130, 246);
    doc.text(title, 20, y);
    doc.setDrawColor(59, 130, 246);
    doc.setLineWidth(0.5);
    doc.line(20, y + 2, 190, y + 2);
  }

  /**
   * Add tool section to PDF
   */
  private static addToolSection(doc: jsPDF, toolName: string, toolData: any, startY: number): void {
    doc.setFontSize(12);
    doc.setTextColor(59, 130, 246);
    doc.text(this.formatToolName(toolName), 20, startY);
    
    const summary = this.generateToolSummary(toolName, toolData);
    doc.setFontSize(10);
    doc.setTextColor(0, 0, 0);
    const lines = doc.splitTextToSize(summary, 170);
    doc.text(lines, 20, startY + 7);
  }

  /**
   * Format tool name for display
   */
  private static formatToolName(toolName: string): string {
    return toolName
      .split(/(?=[A-Z])/)
      .join(' ')
      .replace(/Tool$/, '')
      .trim();
  }

  /**
   * Generate summary text for a tool
   */
  private static generateToolSummary(toolName: string, toolData: any): string {
    if (!toolData || typeof toolData !== 'object') {
      return 'No data available for this tool.';
    }

    // Generate a generic summary
    const keys = Object.keys(toolData);
    if (keys.length === 0) {
      return 'Tool initialized but no data entered.';
    }

    let summary = `This tool contains ${keys.length} data field(s). `;
    
    // Try to extract meaningful information
    if (Array.isArray(toolData)) {
      summary += `Total entries: ${toolData.length}. `;
    } else {
      const dataPoints = keys.filter(key => 
        Array.isArray(toolData[key]) || typeof toolData[key] === 'object'
      );
      if (dataPoints.length > 0) {
        summary += `Key data sections: ${dataPoints.join(', ')}. `;
      }
    }

    return summary;
  }

  /**
   * Determine which phase a tool belongs to
   */
  private static getToolPhase(toolName: string): string {
    const defineTools = ['projectcharter', 'sipoc', 'ctqtree', 'stakeholder', 'voiceofcustomer'];
    const measureTools = ['gagerr', 'histogram', 'pareto', 'controlchart', 'processcapability', 'checksheet', 'datacollection', 'stratification'];
    const analyzeTools = ['fiveWhy', 'regression', 'fishbone', 'boxplot', 'fmea', 'scatterplot'];
    const improveTools = ['solutionprioritization', 'doe', 'pughmatrix', 'kaizen'];
    const controlTools = ['controlplan', 'sop', 'pokayoke', 'auditchecklist', 'monitoring'];

    const lowerTool = toolName.toLowerCase().replace(/\s+/g, '');

    if (defineTools.some(t => lowerTool.includes(t))) return 'define';
    if (measureTools.some(t => lowerTool.includes(t))) return 'measure';
    if (analyzeTools.some(t => lowerTool.includes(t))) return 'analyze';
    if (improveTools.some(t => lowerTool.includes(t))) return 'improve';
    if (controlTools.some(t => lowerTool.includes(t))) return 'control';

    return 'unknown';
  }
}
